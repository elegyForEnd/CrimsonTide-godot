def para(text="", cn=SONG, size=12, bold=False, align=None, indent=True,
         before=0, after=0, spacing=1.5, color=None, italic=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = spacing
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if align is not None:
        p.alignment = align
    if text:
        set_run(p.add_run(text), cn=cn, size=size, bold=bold, color=color, italic=italic)
    return p


def head(text, level=1):
    cfg = {1: (16, 18, 12), 2: (14, 14, 8), 3: (12.5, 12, 6)}
    size, before, after = cfg[level]
    p = doc.add_paragraph()
    p.style = doc.styles["Heading %d" % level]
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.4
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.first_line_indent = Pt(0)
    pf.keep_with_next = True
    pf.keep_together = True
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT if level > 1 else WD_ALIGN_PARAGRAPH.CENTER
    set_run(p.add_run(text), cn=HEI, en=EN, size=size, bold=(level == 1),
            color=RGBColor(0, 0, 0))
    return p


