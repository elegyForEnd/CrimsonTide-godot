def set_run(run, cn=SONG, en=EN, size=12, bold=False, italic=False, color=None):
    run.font.name = en
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn("w:eastAsia"), cn)
    return run


