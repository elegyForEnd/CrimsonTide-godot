def render_scene(s):
    result=f'### {s["id"]}｜{s["title"]}\n\n'
    result+=f'- 对应任务：`{s["task"]}`；路线：`{s["route"]}`。\n'
    result+=f'- 触发：{s["trigger"]}。\n- 画面：{s["visual"]}。\n- 站位／出镜：{s["cast"]}。\n- 结束／交还操作：{s["exit"]}。\n\n'
    for i,line in enumerate(s['lines'],1):
        lid=f'{s["id"]}.L{i:03d}'
        if line['type']=='direction':result+=f'〔演出 {lid}〕{line["text"]}\n\n'
        elif line['type']=='narration':result+=f'〔旁白 {lid}〕{line["text"]}\n\n'
        else:
            name=ACTORS[line['actor']][0]
            expression=line['expression'];pose=line['pose']
            result+=f'**{name}〔{expression}/{pose}｜{lid}〕**：{line["text"]}\n\n'
    return result


