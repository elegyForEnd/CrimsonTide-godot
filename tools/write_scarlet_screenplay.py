def add(sid,task,title,trigger,visual,cast,exit,lines,route='common'):
    parsed=[]
    for raw in lines.strip().splitlines():
        raw=raw.strip()
        if not raw:continue
        head,sep,text=raw.partition('|');assert sep,(sid,raw)
        if head=='@':parsed.append(dict(type='direction',text=text));continue
        bits=head.split(':');actor=bits[0];assert actor in ACTORS,(sid,actor)
        parsed.append(dict(type='narration' if actor=='N' else 'dialogue',actor=actor,
                           expression=bits[1] if len(bits)>1 else 'neutral',
                           pose=bits[2] if len(bits)>2 else 'front',text=text))
    SCENES.append(dict(id=sid,task=task,title=title,trigger=trigger,visual=visual,cast=cast,
                       exit=exit,route=route,lines=parsed))


