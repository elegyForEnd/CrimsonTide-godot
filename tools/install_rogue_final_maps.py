def install():
    data = json.loads(MANIFEST.read_text(encoding='utf-8'))
    selected = {}
    for floor in range(1, 6):
        for kind in ['a6', 'a7', 'shop', 'talent', 'treasure', *SAFE_FALLBACK]:
            key = f'f{floor}-{kind}'
            if key not in data:
                data[key] = copy.deepcopy(data[f'f{floor}-{SAFE_FALLBACK[kind]}'])
            candidates = [REGIONS / f'{key}-flat-night-v7.png']
            if key in PRESERVED:
                candidates.append(REGIONS / f'{key}-smooth-night-v2.png')
            candidates = [p.with_name(p.stem + '-3x.png') for p in candidates] + candidates
            image = next((p for p in candidates if p.exists()), None)
            if image is None:
                # Explicit fallback makes the intermediate project usable.
                alias = f'f{floor}-{SAFE_FALLBACK[kind]}' if kind in SAFE_FALLBACK else key
                suffix = 'seven' if alias.endswith(('a6', 'a7')) else 'safe'
                data[key]['texture'] = f'{alias}-{suffix}-night-v1-3x.png'
                continue
            if key in PROFILES:
                data[key] = copy.deepcopy(PROFILES[key])
            data[key]['texture'] = image.name
            selected[key] = image.name
    MANIFEST.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'Installed {len(selected)}/50 selected night maps; {len(data)} total region profiles')


if __name__ == '__main__':
    install()
