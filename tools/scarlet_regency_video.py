def apply(data):
    for film in data['cinematics']:
        change=CHANGES.get(film['id'],{})
        old_title=film['title'];old_state=film['state']
        if 'title' in change:film['title']=change['title']
        if 'state' in change:film['state']=change['state']
        if 'note' in change:film['note']=change['note']
        for i,s in enumerate(film['segments']):
            p=s['prompt'].replace('summary: '+old_title,'summary: '+film['title'])
            p=p.replace('continuity: '+old_state,'continuity: '+film['state'])
            if i in change.get('actions',{}):
                start,rest=p.split('detailed_description: ',1)
                _,suffix=rest.split('\n',1)
                p=f'{start}detailed_description: 00:00—00:{s["duration"]:02d}，{change["actions"][i]}\n{suffix}'
            s['prompt']=p
    for loop in data['loops']:
        if loop['id']=='cg-01a':
            loop['title']='召回信阅读态'
            loop['prompt']=loop['prompt'].replace('遗书阅读态','召回信阅读态').replace('不新增追缉令','不新增封存令')
        if loop['id']=='cg-01b':
            loop['prompt']=loop['prompt'].replace('两封命令对照态','召信与封存令对照态')
    data['narrative_revision']='regency-compassion-2026-10-16'
    from scarlet_terminology import normalize
    revised=normalize(data)
    data.clear(); data.update(revised)
